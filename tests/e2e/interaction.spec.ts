test('交互提升：逐 token 回看与键盘操作可逆，计算结果不受演示节奏影响', async ({ page }) => {
  const input = { ...DEFAULT_SCENARIO, outputTokens: 8, inputTokens: 16, batch: 2 }
  await page.goto(`/?gl=off&motion=off&simulation=load&scenario=${encodeURIComponent(encodeScenario(input))}`)
  const controls = page.locator('[data-simulation-phase]')
  await controls.focus()
  await page.keyboard.press('ArrowRight')
  await expect(controls.locator('[data-generated-tokens]')).toContainText('1 / 8')
  const firstKV = await controls.locator('[data-simulation-kv]').textContent()
  await page.keyboard.press('ArrowRight')
  await expect(controls.locator('[data-generated-tokens]')).toContainText('2 / 8')
  await page.keyboard.press('ArrowLeft')
  await expect(controls.locator('[data-simulation-kv]')).toHaveText(firstKV!)
  const max = await page.getByLabel('计算进度', { exact: true }).getAttribute('max')
  await page.getByLabel('演示播放速度', { exact: true }).selectOption('4')
  await controls.focus()
  await page.keyboard.press('End')
  await expect(controls).toHaveAttribute('data-simulation-phase', 'complete')
  expect(Number(await page.getByLabel('计算进度', { exact: true }).inputValue())).toBeCloseTo(Number(max), 9)
  await page.keyboard.press('Home')
  await expect(controls.locator('[data-generated-tokens]')).toContainText('0 / 8')
  // The resource summary must not cover the 2D tabs.
  await page.getByRole('tab', {name:'组件树', exact:true}).click()
  await expect(page.getByRole('tab', {name:'组件树', exact:true})).toHaveAttribute('aria-selected','true')
  await page.getByRole('tab', {name:'结构图', exact:true}).click()
  await expect(page).toHaveScreenshot('load-overview.png')
})

test('交互提升：负载驱动可见粒子，暂停与减少动态效果生效且不夺取相机', async ({ page }) => {
  // A long prefill keeps a physical path selected while sampling particle movement.
  const input = { ...DEFAULT_SCENARIO, inputTokens: 32768, cachedTokens: 0, outputTokens: 64, batch: 64 }
  await page.goto(`/?focus=asm.gb300.compute-tray&level=board&simulation=load&scenario=${encodeURIComponent(encodeScenario(input))}`)
  await page.locator('[data-ready="1"]').waitFor()
  const canvas = page.locator('canvas').first()
  await expect(canvas).toHaveAttribute('data-flow-particle-phase', /\d/)
  // Consume any reduced-motion preference persisted by a preceding local visit.
  await page.getByLabel('演示播放速度', { exact: true }).selectOption('0.25')
  const pose = await canvas.getAttribute('data-camera-pose')
  const phase = await canvas.getAttribute('data-flow-particle-phase')
  await page.getByRole('button', { name: '播放演示', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-flow-particles-visible', '1')
  await expect.poll(() => canvas.getAttribute('data-flow-particle-phase')).not.toBe(phase)
  await page.getByRole('button', { name: '暂停演示', exact: true }).click()
  const paused = await canvas.getAttribute('data-flow-particle-phase')
  await page.waitForTimeout(300)
  await expect(canvas).toHaveAttribute('data-flow-particle-phase', paused!)
  await expect(canvas).toHaveAttribute('data-camera-pose', pose!)
  await page.goto(`/?motion=off&focus=asm.gb300.compute-tray&level=board&simulation=load&scenario=${encodeURIComponent(encodeScenario(input))}`)
  await page.locator('[data-ready="1"]').waitFor()
  await page.getByRole('button', { name: '播放演示', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-flow-particles-visible', '0')
  await expect.poll(() => page.getByLabel('计算进度', { exact: true }).inputValue()).not.toBe('0')
})
