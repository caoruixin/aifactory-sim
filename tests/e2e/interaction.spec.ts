import { expect, test } from '@playwright/test'
import { DEFAULT_SCENARIO, encodeScenario } from '../../src/lib/scenario'

test.beforeEach(async ({}, info) => test.skip(info.project.name !== 'desktop', 'Explicit viewport coverage'))

test('交互提升：编辑时结果保持可见，预设与自定义状态有明确反馈', async ({ page }) => {
  await page.goto('/?gl=off&motion=off')
  await page.locator('[data-right-tab="capacity"]').click()
  const panel = page.locator('[data-capacity-panel]')
  const feedback = panel.locator('[data-capacity-feedback]')
  await expect(feedback).toBeInViewport()
  await expect(panel.getByRole('button', { name: '中', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const initial = await feedback.locator('[data-feedback-throughput]').textContent()
  await panel.getByLabel('机架数', { exact: true }).fill('2')
  await expect(feedback.locator('[data-feedback-throughput]')).not.toHaveText(initial!)
  await panel.getByLabel('每副本 batch', { exact: true }).fill('17')
  await expect(panel.locator('[data-scenario-input]')).toContainText('自定义')
  await panel.getByLabel('Rubin 规格配置', { exact: true }).scrollIntoViewIfNeeded()
  await expect(feedback).toBeInViewport()
  await expect(page).toHaveScreenshot('capacity-live-feedback.png')
})

